// Compiles the default library's five switch slots into a C header, so a board
// that has never been given an effect still plays something.
//
// A freshly flashed board used to be dark, and we learned on hardware that a
// dark board is indistinguishable from a failed flash. This makes the default
// state the same five effects the simulator opens with, which also means the
// first thing anyone sees on the neck is something they can already recognise
// from the phone.
//
// Generated, not committed - same rule as the embedded page and the golden
// vectors, and for the same reason: the compiler lives in the browser, so the
// bytecode has to be produced by the browser's compiler or it is a second
// implementation.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defaultLibrary, findPreset, findDefinition, programFor, resolveValues, SLOT_COUNT }
  from './src/model/library.js';
import { encodeProgram } from './src/lang/serialize.js';

const here = dirname(fileURLToPath(import.meta.url));

const f32 = (x) => (Number.isFinite(x) ? `${x.toPrecision(9)}f` : '0.0f');

const bytes = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += 16) {
    out.push('    ' + Array.from(arr.slice(i, i + 16), (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  return out.join(',\n');
};

export function generate() {
  const lib = defaultLibrary();
  const L = [];

  L.push('// GENERATED by web/gen-default-effects.js from the simulator\'s default');
  L.push('// library. Do not edit.');
  L.push('//');
  L.push('// What a board plays before anyone has given it anything: the same five');
  L.push('// effects on the same five switch positions as the simulator opens with.');
  L.push('#pragma once');
  L.push('#include <stddef.h>'); // NULL, for the entries that take no parameters
  L.push('#include <stdint.h>');
  L.push('');
  L.push(`#define EL_DEFAULT_SLOT_COUNT ${SLOT_COUNT}`);
  L.push('');
  L.push('typedef struct {');
  L.push('    const char *name;');
  L.push('    const uint8_t *program;   // ELFX, as web/src/lang/serialize.js writes it');
  L.push('    uint16_t program_len;');
  L.push('    const float *params;');
  L.push('    uint8_t param_count;');
  L.push('} el_default_effect_t;');
  L.push('');

  const slots = [];
  lib.slots.forEach((presetId, i) => {
    const preset = findPreset(lib, presetId);
    const layer = preset.layers[0];
    const def = findDefinition(lib, layer.defId);
    const { program, error } = programFor(def);
    if (!program) throw new Error(`default effect "${def.id}" does not compile: ${error}`);

    const blob = encodeProgram(program);
    const params = resolveValues(program, layer.values);

    L.push(`// slot ${i}: ${preset.name}`);
    L.push(`static const uint8_t EL_DEF_PROG_${i}[${blob.length}] = {`);
    L.push(bytes(blob));
    L.push('};');
    if (params.length) {
      L.push(`static const float EL_DEF_PARAMS_${i}[${params.length}] = { ${Array.from(params, f32).join(', ')} };`);
    }
    L.push('');
    slots.push({ i, name: preset.name, len: blob.length, nParams: params.length });
  });

  L.push('static const el_default_effect_t EL_DEFAULT_EFFECTS[EL_DEFAULT_SLOT_COUNT] = {');
  for (const s of slots) {
    L.push(`    { .name = ${JSON.stringify(s.name)}, .program = EL_DEF_PROG_${s.i}, ` +
           `.program_len = ${s.len}, ` +
           `.params = ${s.nParams ? `EL_DEF_PARAMS_${s.i}` : 'NULL'}, .param_count = ${s.nParams} },`);
  }
  L.push('};');
  L.push('');

  const dir = join(here, '..', 'firmware', 'components', 'core', 'generated');
  mkdirSync(dir, { recursive: true });
  const text = L.join('\n');
  writeFileSync(join(dir, 'el_default_effects.h'), text);
  return { slots: slots.length, names: slots.map((s) => s.name), bytes: text.length };
}
