// Turns web/test/vectors.json into a C header, so the firmware can be held to
// exactly the same golden vectors as the simulator without carrying a JSON
// parser or a base64 decoder into flash.
//
// Generated, not committed - same rule as the embedded page. The contract lives
// in vectors.json; this file only changes its shape.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromBase64 } from './src/lang/serialize.js';
import { FUNCS, VARS } from './src/lang/ops.js';

const here = dirname(fileURLToPath(import.meta.url));

// A float32 printed so a C compiler reproduces the identical bits. 9 digits is
// enough for every float32; the hex form would be safer still but is unreadable
// in a diff, and these numbers get read by humans when a vector fails.
const f32 = (x) => {
  if (Number.isNaN(x)) return '(0.0f/0.0f)';
  if (!Number.isFinite(x)) return x > 0 ? 'INFINITY' : '-INFINITY';
  return `${x.toPrecision(9)}f`;
};

const bytes = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += 16) {
    out.push('    ' + Array.from(arr.slice(i, i + 16), (b) => `0x${b.toString(16).padStart(2, '0')}`).join(', '));
  }
  return out.join(',\n');
};

const hexToBytes = (hex) => {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
};

export function generate() {
  const v = JSON.parse(readFileSync(join(here, 'test', 'vectors.json'), 'utf8'));
  const g = v.geometry;
  const L = [];

  L.push('// GENERATED by web/gen-vectors-h.js from web/test/vectors.json. Do not edit.');
  L.push('//');
  L.push('// The firmware evaluator is held to these and nothing else. They are compiled');
  L.push('// in so the guitar can check itself on a stage with no laptop attached.');
  L.push('#pragma once');
  L.push('#include <math.h>');
  L.push('#include <stdbool.h>');
  L.push('#include <stdint.h>');
  L.push('');
  L.push(`#define EL_VECTORS_FORMAT_VERSION ${v.formatVersion}`);
  L.push(`#define EL_VECTORS_FRAME_RATE ${v.frameRate}`);
  L.push(`#define EL_VECTORS_CASE_COUNT ${v.cases.length}`);
  L.push(`#define EL_VECTORS_MAX_FRAMES ${Math.max(...v.cases.map((c) => c.frames.length))}`);
  L.push(`#define EL_VECTORS_BYTE_COUNT ${v.cases[0].expect[0].length / 2}`);
  L.push('');
  L.push('// Checked against web/src/lang/ops.js by the host test, so a renamed or');
  L.push('// reordered built-in cannot slip past the C side unnoticed.');
  L.push(`#define EL_VECTORS_FUNC_COUNT ${FUNCS.length}`);
  L.push(`#define EL_VECTORS_VAR_COUNT ${VARS.length}`);
  L.push('static const uint8_t EL_VECTORS_FUNC_ARITY[EL_VECTORS_FUNC_COUNT] = {');
  L.push('    ' + FUNCS.map((f) => f.arity).join(', '));
  L.push('};');
  L.push('');
  L.push('// The geometry and output settings are pinned in vectors.json rather than');
  L.push('// taken from the defaults, so a changed default cannot silently rewrite the');
  L.push('// contract. They are pinned here for the same reason.');
  L.push('static const el_geometry_t EL_VECTORS_GEOMETRY = {');
  L.push(`    .scale_length = ${f32(g.scaleLength)},`);
  L.push(`    .frets = ${g.frets},`);
  L.push(`    .leds_per_strip = ${g.ledsPerStrip},`);
  L.push(`    .mapping = ${g.mapping === 'even' ? 'EL_MAP_EVEN' : 'EL_MAP_FRET_MIDPOINT'},`);
  L.push(`    .first_fret = ${g.firstFret},`);
  L.push(`    .nut_to_first_led = ${f32(g.nutToFirstLed)},`);
  L.push(`    .last_led_to_last_fret = ${f32(g.lastLedToLastFret)},`);
  L.push(`    .reversed = { ${g.reversed[0]}, ${g.reversed[1]} },`);
  L.push('};');
  L.push('');
  const profiles = Object.keys(v.outputs);
  profiles.forEach((name, i) => {
    const p = v.outputs[name];
    L.push(`// "${name}"`);
    L.push(`static const el_output_t EL_VECTORS_OUTPUT_${i} = {`);
    L.push(`    .brightness_ceiling = ${f32(p.brightnessCeiling)},`);
    L.push(`    .gamma = ${f32(p.gamma)},`);
    L.push(`    .ma_per_led = ${f32(p.mAPerLed)},`);
    L.push(`    .current_budget = ${f32(p.currentBudget)},`);
    L.push(`    .idle_current = ${f32(p.idleCurrent)},`);
    L.push('};');
  });
  L.push('');
  L.push('typedef struct {');
  L.push('    const char *id;');
  L.push('    const uint8_t *program;');
  L.push('    uint16_t program_len;');
  L.push('    const float *params;');
  L.push('    uint8_t param_count;');
  L.push('    float knob;');
  L.push('    float sw;');
  L.push('    const uint16_t *frames;');
  L.push('    uint8_t frame_count;');
  L.push('    const el_output_t *output;');
  L.push('    bool limited; // recorded as tripping the current limiter');
  L.push('    const uint8_t *expect; // frame-major, EL_VECTORS_BYTE_COUNT per frame');
  L.push('} el_vector_case_t;');
  L.push('');

  v.cases.forEach((c, i) => {
    const prog = fromBase64(c.program);
    L.push(`static const uint8_t EL_VEC_PROG_${i}[${prog.length}] = {`);
    L.push(bytes(prog));
    L.push('};');
    if (c.params.length) {
      L.push(`static const float EL_VEC_PARAMS_${i}[${c.params.length}] = { ${c.params.map(f32).join(', ')} };`);
    }
    L.push(`static const uint16_t EL_VEC_FRAMES_${i}[${c.frames.length}] = { ${c.frames.join(', ')} };`);
    const flat = new Uint8Array(c.expect.length * (c.expect[0].length / 2));
    c.expect.forEach((hex, k) => flat.set(hexToBytes(hex), k * (hex.length / 2)));
    L.push(`static const uint8_t EL_VEC_EXPECT_${i}[${flat.length}] = {`);
    L.push(bytes(flat));
    L.push('};');
    L.push('');
  });

  L.push(`// Named output profiles: ${profiles.join(', ')}. The unclipped one isolates`);
  L.push('// the evaluator; the other is the guitar as it is played, and is the only');
  L.push('// thing that exercises the brightness ceiling and the current limiter.');
  L.push('static const el_vector_case_t EL_VECTORS[EL_VECTORS_CASE_COUNT] = {');
  v.cases.forEach((c, i) => {
    L.push('    {');
    L.push(`        .id = ${JSON.stringify(c.id)},`);
    L.push(`        .program = EL_VEC_PROG_${i}, .program_len = ${fromBase64(c.program).length},`);
    L.push(`        .params = ${c.params.length ? `EL_VEC_PARAMS_${i}` : 'NULL'}, .param_count = ${c.params.length},`);
    L.push(`        .knob = ${f32(c.knob)}, .sw = ${f32(c.sw)},`);
    L.push(`        .frames = EL_VEC_FRAMES_${i}, .frame_count = ${c.frames.length},`);
    L.push(`        .output = &EL_VECTORS_OUTPUT_${profiles.indexOf(c.output)}, .limited = ${!!c.limited},`);
    L.push(`        .expect = EL_VEC_EXPECT_${i},`);
    L.push('    },');
  });
  L.push('};');
  L.push('');

  const dir = join(here, '..', 'firmware', 'components', 'core', 'generated');
  mkdirSync(dir, { recursive: true });
  const text = L.join('\n');
  writeFileSync(join(dir, 'el_vectors.h'), text);
  return { cases: v.cases.length, bytes: text.length };
}
